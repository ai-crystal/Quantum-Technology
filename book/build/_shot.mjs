import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true, args:['--no-sandbox']});
const p = await b.newPage();
await p.setViewport({width:1440,height:900});
await p.goto('http://localhost:8099/', {waitUntil:'networkidle2', timeout:60000});
await new Promise(r=>setTimeout(r,2500));
await p.screenshot({path:'../../_private/site_home.png'});
await p.goto('http://localhost:8099/#/book/chapters/ch01', {waitUntil:'networkidle2', timeout:60000});
await new Promise(r=>setTimeout(r,3000));
await p.screenshot({path:'../../_private/site_ch01.png'});
await b.close();
console.log('done');
