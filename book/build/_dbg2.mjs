import fs from 'fs';
import { getDocument } from 'pdfjs-dist/legacy/build/pdf.mjs';
const data = new Uint8Array(fs.readFileSync('.tmp/body.pdf'));
const doc = await getDocument({ data }).promise;
const out = await doc.getOutline();
const t = out[1].title;
console.log(JSON.stringify(t), [...t].map(c => c.charCodeAt(0).toString(16)).join(' '));
const heads = fs.readFileSync('../chapters/ch01.md','utf8').split('\n').filter(l=>l.startsWith('# '));
const h = heads[0].replace(/^#\s*/,'').trim();
console.log(JSON.stringify(h), [...h].map(c => c.charCodeAt(0).toString(16)).join(' '));
